const fs = require("fs");
const path = "client/src/components/pages/Authentication/Login.jsx";
let src = fs.readFileSync(path, "utf8");
console.log("has Username label:", src.includes('labelName="Username"'));
src = src.split('labelName="Username"').join('labelName="Логин"');
src = src.split('labelName="Password"').join('labelName="Пароль"');
src = src.split('required("Field is required")').join('required("Обязательное поле")');
src = src.split('&& "Login"}').join('&& "Войти"}');
fs.writeFileSync(path, src, "utf8");
const check = fs.readFileSync(path, "utf8");
console.log("after write, has Логин:", check.includes("Логин"));
console.log("after write, has Username label:", check.includes('labelName="Username"'));
